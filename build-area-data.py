#!/usr/bin/env python3
"""Build lib/area-data.ts from the CMAP Community Data Snapshots CSV (ACS 2020-2024, Table C16001).

Run from the repo root:  python3 scripts/build-area-data.py
Reads data/raw/CMAP-Community-Data-Snapshots-2026.csv. Signage fields (visibility,
signsSurveyed) are left out until the field survey exists.
"""
import csv, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'data/raw/CMAP-Community-Data-Snapshots-2026.csv'
OUT = ROOT / 'lib/area-data.ts'

GROUPS = [
    ('SPANISH', 'Spanish'), ('SLAVIC', 'Slavic languages'), ('CHINESE', 'Chinese'),
    ('TAGALOG', 'Tagalog'), ('ARABIC', 'Arabic'), ('KOREAN', 'Korean'),
    ('OTHER_ASIAN', 'Other Asian & Pacific Island'), ('OTHER_EURO', 'Other Indo-European'),
    ('OTHER_UNSPEC', 'Other / unspecified'),
]

rows = list(csv.DictReader(open(SRC, encoding='utf-8-sig')))
assert len(rows) == 77, len(rows)
out = {}
for r in rows:
    n = int(r['GEOID'])
    pop = float(r['POP_OV5'])
    ne = float(r['NOT_ENGLISH'])
    assert abs(sum(float(r[k]) for k, _ in GROUPS) - ne) < 0.01, n
    assert abs(float(r['ENGLISH']) + ne - pop) < 0.01, n
    langs = [(name, round(float(r[k]) / pop * 100, 1)) for k, name in GROUPS]
    langs = sorted([l for l in langs if l[1] > 0], key=lambda l: -l[1])
    out[n] = dict(
        name=r['GEOG'],
        speakers=round(ne / pop * 100, 1),
        lep=round(float(r['LING_ISO']) / pop * 100, 1),
        languages=langs,
    )

lines = [
    "import type { AreaMeasurements, Snapshot } from './data'",
    '',
    '/*',
    ' * Generated by scripts/build-area-data.py. Do not edit the census numbers by hand;',
    ' * re-run the script instead.',
    ' *',
    ' * Source: CMAP Community Data Snapshots (2026 release), from the U.S. Census Bureau',
    ' * 2020-2024 American Community Survey 5-year estimates, Table C16001 (language spoken',
    ' * at home, population 5 years and over). See data/raw/SOURCE.md.',
    ' *',
    ' * AREA_DATA is keyed by official community area number (1-77):',
    ' *   speakers: % of residents 5+ who speak a language other than English at home',
    ' *   lep:      % of residents 5+ who speak English less than "very well"',
    ' *   languages: home-language groups, % of residents 5+, largest first',
    ' *   visibility / signsSurveyed: from our own sign survey, added later. An area is only',
    ' *     scored at MIN_SIGNS_SURVEYED signs or more (see lib/metrics.ts).',
    ' *',
    ' * SNAPSHOT_DATA holds individual field observations (photos/notes of real signs).',
    ' */',
    '',
    'export const AREA_DATA: Partial<Record<number, AreaMeasurements>> = {',
]
for n in sorted(out):
    d = out[n]
    lines.append(f"  // {d['name']}")
    lines.append(f"  {n}: {{")
    lines.append(f"    speakers: {d['speakers']},")
    lines.append(f"    lep: {d['lep']},")
    lines.append('    languages: [')
    for name, pct in d['languages']:
        lines.append(f"      {{ language: '{name}', pct: {pct} }},")
    lines.append('    ],')
    lines.append('  },')
lines += ['}', '', 'export const SNAPSHOT_DATA: Snapshot[] = []', '']
OUT.write_text('\n'.join(lines))
print('wrote', OUT, len(out), 'areas')
